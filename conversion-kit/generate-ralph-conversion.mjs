#!/usr/bin/env node
/**
 * Generates prd.md, PROMPT.md, activity.md, and CHECKS.md in the target Astro repo
 * for Ralph-style iterative Claude conversion (one task per session).
 *
 * The generated PRD encodes the target architecture from
 * `docs/TEMPLATE-CONVERSION-GUIDE.md` (in template.location). Tasks are grouped
 * roughly along Conversion Guide phases A→E so Ralph can finish a mechanical
 * Lovable→scaffold migration into a fully data-driven Astro site.
 *
 * Usage:
 *   node conversion-kit/generate-ralph-conversion.mjs --dest /path/to/astro-repo [--src-repo /path/to/lovable]
 */

import fs from 'fs';
import path from 'path';

function parseArgs(argv) {
  const out = { dest: null, srcRepo: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--dest' && argv[i + 1]) out.dest = path.resolve(argv[++i]);
    if (argv[i] === '--src-repo' && argv[i + 1]) out.srcRepo = path.resolve(argv[++i]);
  }
  return out;
}

