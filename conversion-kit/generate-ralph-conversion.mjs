function main() {
  const { dest, srcRepo } = parseArgs(process.argv.slice(2));
  if (!dest) {
    console.error(
      'Usage: node conversion-kit/generate-ralph-conversion.mjs --dest <astro-repo> [--src-repo <lovable>]'
    );
    process.exit(1);
  }

  const meta = [];
  if (srcRepo) meta.push(`Source Lovable repo (reference): \`${srcRepo}\``);
  meta.push(`Generated for destination: \`${dest}\``);

  const prdPath = path.join(dest, 'prd.md');
  const promptPath = path.join(dest, 'PROMPT.md');
  const activityPath = path.join(dest, 'activity.md');
  const checksPath = path.join(dest, 'CHECKS.md');

  const taskBlock = '```json\n' + JSON.stringify(TASKS_JSON, null, 2) + '\n```\n';

  fs.writeFileSync(
    prdPath,
    PRD_INTRO +
      '\n' +
      meta.map((m) => `> ${m}\n`).join('') +
      '\n' +
      taskBlock +
      '\n## Agent instructions\n\n1. Read `activity.md` first.\n2. Pick the next task with `"passes": false` (top-down order).\n3. Implement every listed step.\n4. Flip `"passes": true` only when the task is fully done and verified.\n5. Append a dated entry to `activity.md`.\n',
    'utf-8'
  );

  fs.writeFileSync(promptPath, PROMPT_BODY, 'utf-8');

  fs.writeFileSync(
    activityPath,
    `# Conversion — Activity Log

## Current Status
**Last Updated:** (not started)
**Tasks Completed:** 0 / ${TASKS_JSON.length}

---

## Session Log

`,
    'utf-8'
  );

  fs.writeFileSync(checksPath, CHECKS_MD, 'utf-8');

  console.log(`Wrote: ${prdPath}`);
  console.log(`Wrote: ${promptPath}`);
  console.log(`Wrote: ${activityPath}`);
  console.log(`Wrote: ${checksPath}`);
}

main();
