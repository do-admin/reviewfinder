import { defineConfig } from 'astro/config';
import react from '@astrojs/react';
import dotenv from 'dotenv';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { normalizePublicUrl } from './scripts/lib/normalize-public-url.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Load .env.local and .env so process.env has them when config is evaluated
dotenv.config({ path: '.env.local', quiet: true });
dotenv.config();

// Astro.site is the canonical host (canonical/OG/schema). Read from data:
// `clientDomain` first, `deployDomain` as fallback. NOT from DEPLOY_DOMAIN env
// (that's the raw deploy target, not necessarily the canonical host).
function getFallbackSiteUrl() {
  try {
    const websitesPath = path.resolve(
      __dirname,
      'src/data/current/websites.json'
    );
    const data = JSON.parse(fs.readFileSync(websitesPath, 'utf-8'));
    const websites = Array.isArray(data) ? data : (data.websites ?? []);
    const topLevelDomain = !Array.isArray(data) ? data.clientDomain : undefined;
    const siteId = process.env.SITE_ID ?? '';
    const selectedWebsite = siteId
      ? websites.find((w) => w?.id === siteId)
      : websites[0];
    const domain =
      selectedWebsite?.clientDomain ??
      topLevelDomain ??
      selectedWebsite?.deployDomain ??
      websites[0]?.clientDomain ??
      topLevelDomain ??
      websites[0]?.deployDomain;
    if (domain) {
      const url = domain.startsWith('http') ? domain : `https://${domain}`;
      return normalizePublicUrl(url);
    }
  } catch {
    // No current client data available
  }
  return normalizePublicUrl('https://example.com');
}

// Sitemap is generated by scripts/generate-sitemap-from-dist.mjs after build
// (avoids @astrojs/sitemap dependency on astro:routes:resolved which can be undefined)
export default defineConfig({
  site: normalizePublicUrl(process.env.SITE_URL || getFallbackSiteUrl()),
  output: 'static',
  integrations: [react()],
  build: {
    // Tailwind v4 global CSS can exceed vite.build.assetsInlineLimit; force inline
    // so no render-blocking /_astro/*.css link (see Astro build.inlineStylesheets).
    inlineStylesheets: 'always',
  },
  vite: {
    build: {
      assetsInlineLimit: 16 * 1024,
    },
    css: {
      postcss: './postcss.config.mjs',
    },
    resolve: {
      alias: {
        '@/data': path.resolve(__dirname, 'src/data/current'),
      },
      dedupe: ['react', 'react-dom'],
    },
    // Expose SITE_ID so local dev can control which website is shown (e.g. in .env.local)
    define: {
      'import.meta.env.SITE_ID': JSON.stringify(process.env.SITE_ID ?? ''),
      'import.meta.env.CLIENT_ID': JSON.stringify(process.env.CLIENT_ID ?? ''),
    },
  },
});
